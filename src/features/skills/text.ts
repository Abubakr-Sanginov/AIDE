const TEXT: Record<Lang, SkillText> = { en, ru, de, fr, es, pt, it, zh, ja, ko, tg };

export function useSkillText(): SkillText {
  const { lang } = useI18n();
  return TEXT[lang] ?? en;
}

export function fill(s: string, params: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}
