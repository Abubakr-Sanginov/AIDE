export type DesignText = typeof en;

export function designText(lang: string): DesignText {
  return lang === "tg" ? tg : isRuLike(lang) ? ru : en;
}

export function useDesignText(): DesignText {
  const { lang } = useI18n();
  return designText(lang);
}

export function currentDesignText(): DesignText {
  try {
    return designText(localStorage.getItem("aide.lang") ?? "en");
  } catch {
    return en;
  }
}
