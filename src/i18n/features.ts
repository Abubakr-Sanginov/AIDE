export type FeatureText = typeof ru;

/** For code outside React (stores, command palette). */
export function featureText(): FeatureText {
  try {
    const l = localStorage.getItem("aide.lang");
    return l === "tg" ? tg : isRuLike(l) ? ru : en;
  } catch {
    return en;
  }
}

export function useFeatureText(): FeatureText {
  const { lang } = useI18n();
  return lang === "tg" ? tg : isRuLike(lang) ? ru : en;
}

export function fmt(s: string, params: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}
